    public function run(): void
    {
        $dilewati = [];

        foreach ($this->data() as $row) {
            if ($row['latitude'] === null || $row['longitude'] === null) {
                $dilewati[] = $row['nama'];
                continue;
            }

            LokasiAngkut::updateOrCreate(
                ['nama' => $row['nama']],
                $row + ['aktif' => true]
            );
        }

        if ($dilewati) {
            $this->command?->warn('Dilewati (belum ada koordinat): ' . implode(', ', $dilewati));
        }
    }

